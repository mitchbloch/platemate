import { describe, expect, it } from "vitest";
import { cleanInlineText, decodeEntities, extractEmbeddedJson, extractMeta, htmlToText, vttToText } from "../text";

describe("decodeEntities", () => {
  it("decodes named, decimal and hex entities including fractions", () => {
    expect(decodeEntities("1 &frac12; cups &amp; 2&frac14; tsp &#8211; 350&deg;F &#x2019;")).toBe("1 ½ cups & 2¼ tsp – 350°F ’");
  });

  it("handles double-encoded CMS output", () => {
    expect(decodeEntities("Grandma&amp;#39;s pie")).toBe("Grandma's pie");
  });

  it("leaves unknown entities and stray ampersands alone", () => {
    expect(decodeEntities("salt & pepper &bogus; &#0;")).toBe("salt & pepper &bogus; &#0;");
  });
});

describe("htmlToText", () => {
  it("keeps recipe text and drops scripts, styles and chrome", () => {
    const html = `<html><head><style>.x{}</style><script>var a=1</script></head><body>
      <header>Site Logo</header><nav>Home | Recipes</nav>
      <h1>Lentil Soup</h1><p>Cozy &amp; cheap.</p>
      <ul><li>1 cup lentils</li><li>2&frac12; cups stock</li></ul>
      <ol><li>Simmer.</li><li>Serve<br>hot.</li></ol>
      <!-- tracking --><footer>© 2026</footer></body></html>`;
    expect(htmlToText(html)).toBe("Lentil Soup\n\nCozy & cheap.\n\n- 1 cup lentils\n\n- 2½ cups stock\n\n- Simmer.\n\n- Serve\nhot.");
  });

  it("is much smaller than the HTML it came from", () => {
    const html = `<div class="${"x".repeat(500)}"><span data-a="${"y".repeat(500)}">Text</span></div>`;
    expect(htmlToText(html)).toBe("Text");
  });
});

describe("cleanInlineText", () => {
  it("strips tags and collapses whitespace", () => {
    expect(cleanInlineText("  <p>Preheat  the <b>oven</b>\n to 400&deg;F.</p> ")).toBe("Preheat the oven to 400°F.");
  });
});

describe("extractMeta", () => {
  it("reads property or name in either attribute order and decodes entities (regression)", () => {
    const html = `<meta content="Mac &amp; cheese" property="og:title"><meta name="description" content='Easy&#39;s best'>`;
    expect(extractMeta(html, "og:title")).toBe("Mac & cheese");
    expect(extractMeta(html, "description")).toBe("Easy's best");
  });

  it("keeps apostrophes inside double-quoted values (regression)", () => {
    expect(extractMeta(`<meta property="og:description" content="Grandma's chili, 3 ways">`, "og:description")).toBe(
      "Grandma's chili, 3 ways",
    );
  });

  it("returns null when missing or empty", () => {
    expect(extractMeta(`<meta property="og:title" content="">`, "og:title")).toBeNull();
    expect(extractMeta("<p>no meta</p>", "og:title")).toBeNull();
  });
});

describe("vttToText", () => {
  it("drops header, cue ids, timings and rolling duplicates", () => {
    const vtt = `WEBVTT

NOTE generated by ASR
spanning two lines

1
00:00:00.000 --> 00:00:01.500
Get your onions,

2
00:00:01.500 --> 00:00:02.000
Get your onions,

3
00:00:02.000 --> 00:00:04.000
bell pepper &amp; <c>garlic</c><00:00:03.100> chopped`;
    expect(vttToText(vtt)).toBe("Get your onions,\nbell pepper & garlic chopped");
  });

  it("handles CRLF line endings and empty input", () => {
    expect(vttToText("WEBVTT\r\n\r\n00:00.000 --> 00:01.000\r\nHello\r\n")).toBe("Hello");
    expect(vttToText("")).toBe("");
  });
});

describe("extractEmbeddedJson", () => {
  it("parses an object whose strings contain braces and `};`", () => {
    const html = `<script>var ytInitialPlayerResponse = {"videoDetails":{"shortDescription":"Mix it };\\n then {fold}\\" done"}};var x = 1;</script>`;
    expect(extractEmbeddedJson(html, /ytInitialPlayerResponse\s*=\s*/)).toEqual({
      videoDetails: { shortDescription: 'Mix it };\n then {fold}" done' },
    });
  });

  it("skips a malformed earlier match and uses the next one", () => {
    const html = `ytInitialPlayerResponse = {broken}; ytInitialPlayerResponse = {"ok":true};`;
    expect(extractEmbeddedJson(html, /ytInitialPlayerResponse\s*=\s*/)).toEqual({ ok: true });
  });

  it("reads JSON from a script tag marker", () => {
    const html = `<script id="__UNIVERSAL_DATA_FOR_REHYDRATION__" type="application/json">{"__DEFAULT_SCOPE__":{"a":1}}</script>`;
    expect(extractEmbeddedJson(html, /<script[^>]*id="__UNIVERSAL_DATA_FOR_REHYDRATION__"[^>]*>/)).toEqual({
      __DEFAULT_SCOPE__: { a: 1 },
    });
  });

  it("returns null when the marker is absent or the object never closes", () => {
    expect(extractEmbeddedJson("<p>nothing</p>", /ytInitialPlayerResponse\s*=\s*/)).toBeNull();
    expect(extractEmbeddedJson('ytInitialPlayerResponse = {"a":', /ytInitialPlayerResponse\s*=\s*/)).toBeNull();
  });
});
